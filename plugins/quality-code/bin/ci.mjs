#!/usr/bin/env node
// The testing phases of the project in one run, for a GitHub Actions or GitLab CI job (or a terminal):
// node bin/ci.mjs [--suite full|backend|frontend] [--all] [--base REF] [--flaky N] [--json] [--junit FILE] [--no-audit]
// node bin/ci.mjs --init github|gitlab [--changed] [--write]   (the CI file runs every test of the test folders; --changed: only what the branch touched)
// It reads what the branch changed (against the merge request's or pull request's target) and RUNS only that:
// the specs that were added or changed, by module (a backend layer, an e2e folder), through the pipeline (tests,
// assertions, types, mutation). A side whose code changed but no spec did runs its whole suite; a side with no
// change is skipped. On the default branch, with --all, or when the changes cannot be read (no git, no base,
// a shallow clone) everything runs, so nothing is silently left out. Frozen evals run with any test change.
// A phase that fails does not stop the next one: the job shows everything that is wrong at once. No model is
// involved: the scripts decide.
// Exit 0 every phase green (or nothing changed), 1 a check failed or a test is red, 2 usage or config error,
// 3 something could not run (never a pass).
import { existsSync, mkdirSync, readFileSync, appendFileSync, writeFileSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { adaptersForSide, adaptersOf } from '../lib/base/stack.mjs'
import { loadConfig, projectRoot } from '../lib/base/config.mjs'
import { runnerLabel } from '../lib/base/backends.mjs'
import { projectSpecs } from '../lib/report/quality-program.mjs'
import { moduleOf, planChanges } from '../lib/base/changes.mjs'
import { detect } from './branch.mjs'
import { formatCard } from '../lib/pipeline/card.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const USAGE = 'usage: ci.mjs [--suite full|backend|frontend] [--all] [--base REF] [--flaky N] [--json] [--junit FILE] [--no-audit] | ci.mjs --init github|gitlab [--changed] [--write]'
const SUITES = ['full', 'backend', 'frontend']
const WORDS = { green: 'green', tests_red: 'tests red', checks_failed: 'checks failed', not_verified: 'not verified', skipped: 'skipped' }
const ORDER = { green: 0, skipped: 0, tests_red: 1, checks_failed: 1, not_verified: 3 }

/** The branch a pull request or merge request targets, as the CI tells it; null outside one. */
export const baseFromEnv = env => env.GITHUB_BASE_REF || env.CI_MERGE_REQUEST_TARGET_BRANCH_NAME || null

export const providerOf = env => (env.GITHUB_ACTIONS ? 'github' : env.GITLAB_CI ? 'gitlab' : null)

function parse(argv) {
  const a = { suite: 'full', json: false, noAudit: false, write: false, all: false, changed: false }
  for (let i = 0; i < argv.length; i++) {
    const x = argv[i]
    if (['--suite', '--flaky', '--junit', '--init', '--base'].includes(x)) {
      const v = argv[++i]
      if (v === undefined || v.startsWith('-') || !v.trim()) throw new Error(`${x} needs a value, not "${v ?? ''}"`)
      a[x.slice(2)] = v
    } else if (x === '--json') a.json = true
    else if (x === '--no-audit') a.noAudit = true
    else if (x === '--write') a.write = true
    else if (x === '--all') a.all = true
    else if (x === '--changed') a.changed = true
    else throw new Error(`unknown option ${x}`)
  }
  if (!SUITES.includes(a.suite)) throw new Error(`--suite must be full, backend or frontend, not "${a.suite}"`)
  if (a.flaky !== undefined && !/^[1-9]\d*$/.test(a.flaky)) throw new Error(`--flaky must be a whole number of 1 or more, not "${a.flaky}"`)
  if (a.init !== undefined && !['github', 'gitlab'].includes(a.init)) throw new Error(`--init must be github or gitlab, not "${a.init}"`)
  if ((a.write || a.changed) && a.init === undefined) throw new Error(`${a.write ? '--write' : '--changed'} goes with --init`)
  return a
}

/** The CI file for a provider: the plugin fetched at the version this one is, then one command. */
export function template(provider, version, { changed = false } = {}) {
  const tag = `quality-code--v${version}`
  const fetch = `git clone --quiet --depth 1 --branch ${tag} https://github.com/vissz28/agentic-testing.git .quality-code-plugin`
  const run = `node .quality-code-plugin/plugins/quality-code/bin/ci.mjs${changed ? '' : ' --all'} --junit quality-code-junit.xml`
  const what = changed ? 'only the tests the branch touched, per module' : 'every test of the project\'s test folders'
  if (provider === 'github') {
    return `# Quality Code: ${what} (backend and frontend) on each push and pull request.
# Generated by: node bin/ci.mjs --init github${changed ? ' --changed' : ''}
name: quality-code
on: [push, pull_request]
jobs:
  quality-code:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with: { fetch-depth: 0 }
      - uses: actions/setup-node@v4
        with: { node-version: 22 }
      # Install your project's own dependencies and runners here (npm ci, pip install, a JDK, Go, .NET).
      - run: npm ci
      - run: ${fetch}
      - run: ${run}
      - uses: actions/upload-artifact@v4
        if: always()
        with: { name: quality-code-junit, path: quality-code-junit.xml }
`
  }
  return `# Quality Code: ${what} (backend and frontend) on each merge request and push to the default branch.
# Generated by: node bin/ci.mjs --init gitlab${changed ? ' --changed' : ''}
quality-code:
  image: node:22
  rules:
    - if: $CI_PIPELINE_SOURCE == "merge_request_event"
    - if: $CI_COMMIT_BRANCH == $CI_DEFAULT_BRANCH
  variables:
    GIT_DEPTH: "0"
  before_script:
    # Install your project's own dependencies and runners here (npm ci, pip install, a JDK, Go, .NET).
    - npm ci
    - ${fetch}
  script:
    - ${run}
  artifacts:
    when: always
    reports:
      junit: quality-code-junit.xml
`
}

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

/** One JUnit testcase per phase, so GitLab's merge request shows them and a failed phase is a failure. */
export function junit(phases) {
  const bad = phases.filter(p => ORDER[p.verdict] > 0)
  const cases = phases.map(p => {
    const body = p.verdict === 'skipped' ? '<skipped/>' : ORDER[p.verdict] > 0 ? `<failure message="${esc(WORDS[p.verdict])}">${esc(p.detail)}</failure>` : ''
    return `  <testcase classname="quality-code" name="${esc(p.name)}">${body}</testcase>`
  })
  return `<?xml version="1.0" encoding="UTF-8"?>\n<testsuite name="quality-code" tests="${phases.length}" failures="${bad.length}">\n${cases.join('\n')}\n</testsuite>\n`
}

function runPhase(root, job, a, env, range) {
  const what = job.specs ? job.specs : ['--suite', job.suite]
  const args = [join(HERE, 'pipeline.mjs'), ...what, ...(range ? ['--range', range] : []), '--json', ...(a.flaky ? ['--flaky', a.flaky] : []), ...(a.noAudit ? ['--no-audit'] : [])]
  const r = spawnSync(process.execPath, args, { cwd: root, env: { ...env, CI: '1' }, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024 })
  let outcome = null
  try { outcome = JSON.parse(r.stdout) } catch {}
  return { r, outcome }
}

export async function main(argv = process.argv.slice(2), env = process.env, cwd = process.cwd(), { stdout = s => process.stdout.write(s), stderr = s => process.stderr.write(s) } = {}) {
  let a
  try { a = parse(argv) } catch (e) { stderr(`${e.message}\n${USAGE}\n`); return 2 }
  const root = projectRoot(env, cwd)
  if (a.init !== undefined) {
    const version = JSON.parse(readFileSync(join(HERE, '..', '.claude-plugin', 'plugin.json'), 'utf8')).version
    const text = template(a.init, version, { changed: a.changed })
    if (!a.write) { stdout(text); return 0 }
    // Never overwrite: an existing GitLab file gets the job in a file of its own, to include.
    const target = a.init === 'github' ? '.github/workflows/quality-code.yml' : existsSync(join(root, '.gitlab-ci.yml')) ? '.gitlab/quality-code.gitlab-ci.yml' : '.gitlab-ci.yml'
    if (existsSync(join(root, target))) { stderr(`${target} is there already: not overwritten. Print it instead: ci.mjs --init ${a.init}\n`); return 2 }
    mkdirSync(dirname(join(root, target)), { recursive: true })
    writeFileSync(join(root, target), text)
    stdout(`ok: wrote ${target}\n`)
    if (target === '.gitlab/quality-code.gitlab-ci.yml') stdout('Add it to your .gitlab-ci.yml:\ninclude:\n  - local: .gitlab/quality-code.gitlab-ci.yml\n')
    return 0
  }
  const cfg = loadConfig(root)
  if (!cfg.ok) { stderr(`${cfg.errors.join('\n')}\n`); return 2 }
  if (cfg.source === 'personal') { stderr('CI needs a repo with its own .claude/quality-code.json (run /quality-code:setup in the project).\n'); return 2 }
  const config = cfg.config
  const has = adaptersOf(config)
  const sides = a.suite === 'full' ? ['backend', 'frontend'] : [a.suite]
  if (a.suite !== 'full' && !adaptersForSide(a.suite, config).some(x => has.includes(x))) { stderr(`This project has no ${a.suite} tests: its adapter is ${config.adapter}.\n`); return 2 }
  const phases = []
  const show = s => { if (!a.json) stdout(s) }
  const provider = providerOf(env)
  const known = projectSpecs(root, config)

  // What to run: everything (--all, the default branch, or when the changes cannot be read), else only what the branch touched.
  const wanted = sides.filter(side => adaptersForSide(side, config).some(x => has.includes(x)))
  let scope = { mode: 'all', why: 'every phase was asked for (--all)' }
  let plan = null
  if (!a.all) {
    const det = detect(root, config, { base: a.base ?? baseFromEnv(env) })
    if (!det.isRepo) scope = { mode: 'all', why: 'this is not a git checkout, so what changed cannot be read' }
    else if (!det.base || !det.mergeBase) scope = { mode: 'all', why: 'the branch it started from was not found (fetch the full history: fetch-depth 0 on GitHub, GIT_DEPTH 0 on GitLab)' }
    else if (det.shallow) scope = { mode: 'all', why: 'the checkout is shallow, so what changed cannot be read (fetch-depth 0 on GitHub, GIT_DEPTH 0 on GitLab)' }
    else if (det.onBase) scope = { mode: 'all', why: `this is ${det.base.replace(/^origin\//, '')} itself: the whole suite runs on the default branch` }
    else {
      plan = planChanges(det.files, config, known)
      scope = { mode: 'changes', base: det.base, why: `changes since ${det.base}: ${det.counts.test} test file${det.counts.test === 1 ? '' : 's'}, ${det.counts.code} code file${det.counts.code === 1 ? '' : 's'}` }
    }
  }
  show(`quality-code ci${provider ? ` · ${provider === 'github' ? 'GitHub Actions' : 'GitLab CI'}` : ''} · ${a.suite}\n${scope.mode === 'all' ? `Running everything: ${scope.why}.` : `Running only what changed (${scope.why}).`}\n`)

  // One run per module: the changed specs of a module together, or a side's whole suite.
  const jobs = []
  if (scope.mode === 'all') for (const side of wanted) jobs.push({ side, name: side, suite: side })
  else {
    for (const side of wanted) {
      const p = plan[side]
      if (p.specs.size) {
        const groups = new Map()
        for (const path of p.specs.keys()) {
          const mod = moduleOf(config, root, path, known.find(k => k.path === path).adapter)
          groups.set(mod, [...(groups.get(mod) ?? []), path])
        }
        for (const [mod, specs] of groups) jobs.push({ side, name: `${side}/${mod}`, specs })
      } else if (p.source || p.shared) jobs.push({ side, name: side, suite: side, note: p.shared && !p.source ? 'a shared config or dependency file changed' : `${side} code changed and no ${side} spec did` })
      else phases.push({ name: side, verdict: 'skipped', detail: `nothing changed in ${side}` })
    }
  }
  for (const side of sides.filter(x => !wanted.includes(x))) { phases.push({ name: side, verdict: 'skipped', detail: `no ${side} tests in this project` }); show(`\n== ${side} · skipped (no ${side} tests in this project)\n`) }
  const anyTest = scope.mode === 'all' || sides.some(side => plan?.[side]?.specs.size)
  if (a.suite === 'full' && anyTest) {
    const e = spawnSync(process.execPath, [join(HERE, 'evals.mjs')], { cwd: root, env, encoding: 'utf8' })
    const verdict = e.status === 0 ? 'green' : e.status === 3 ? 'skipped' : e.status === 1 ? 'checks_failed' : 'not_verified'
    phases.unshift({ name: 'evals', verdict, detail: (e.stdout + e.stderr).trim() })
    show(`\n== evals · ${WORDS[verdict]}${e.status === 3 ? ' (no frozen evals in this project)' : ''}\n${verdict === 'skipped' ? '' : `${phases[0].detail}\n`}`)
  }
  for (const side of wanted) if (phases.some(p => p.name === side && p.verdict === 'skipped' && p.detail.startsWith('nothing changed'))) show(`\n== ${side} · skipped (nothing changed in ${side})\n`)

  for (const job of jobs) {
    const want = adaptersForSide(job.side, config).filter(x => has.includes(x))
    const label = want.map(runnerLabel).join(' + ')
    const specs = job.specs ?? known.filter(k => want.includes(k.adapter)).map(k => k.path)
    if (!specs.length) {
      // Zero tests must never read as a pass.
      phases.push({ name: job.name, verdict: 'not_verified', detail: `no ${label} spec files found in the project's test folders` })
      show(`\n== ${job.name} (${label}) · not verified\nNo ${label} spec files found in the project's test folders.\n`)
      continue
    }
    if (job.note) show(`\n(${job.note}: running the whole ${job.side} suite)`)
    const { r, outcome } = runPhase(root, job, a, env, scope.mode === 'changes' && job.specs ? `${scope.base}...HEAD` : null)
    if (!outcome) {
      const detail = (r.stderr || r.stdout || 'the pipeline did not answer').trim()
      phases.push({ name: job.name, verdict: 'not_verified', detail })
      show(`\n== ${job.name} (${label}) · not verified\n${detail}\n`)
      continue
    }
    const tests = outcome.steps?.find(x => x.check === 'tests')?.data ?? {}
    phases.push({ name: job.name, verdict: outcome.verdict, detail: formatCard(outcome, { specs }).replace(/\nPIPELINE_JSON:.*$/s, ''), runner: label, specs: specs.length, passed: tests.passed, failed: tests.failed })
    show(`\n== ${job.name} (${label}) · ${WORDS[outcome.verdict] ?? outcome.verdict}\n${phases.at(-1).detail}\n`)
  }
  if (scope.mode === 'changes' && !jobs.length) show('\nNothing to test: no backend or frontend test or code changed.\n')

  const worst = phases.reduce((m, p) => Math.max(m, ORDER[p.verdict] ?? 3), 0)
  // Nothing run is a pass only when the changes said there was nothing to test; with everything asked for, it is not verified.
  const code = worst === 0 && phases.every(p => p.verdict === 'skipped') && scope.mode === 'all' ? 3 : worst
  const result = code === 0 ? (jobs.length ? 'PASSED' : 'NOTHING TO TEST') : code === 1 ? 'FAILED' : 'NOT VERIFIED'
  const width = Math.max(9, ...phases.map(p => p.name.length))
  const table = phases.map(p => `  ${p.name.padEnd(width)} ${WORDS[p.verdict] ?? p.verdict}${p.passed !== undefined ? ` · ${p.passed} passed · ${p.failed} failed` : ''}`)
  if (a.json) stdout(`${JSON.stringify({ result, exit: code, provider, phases: phases.map(({ detail, ...p }) => p) })}\n`)
  else stdout(`\nSummary\n${table.join('\n')}\nResult: ${result}${code ? ` (exit ${code})` : ''}\n`)

  if (a.junit) {
    try { mkdirSync(dirname(resolve(root, a.junit)), { recursive: true }); writeFileSync(resolve(root, a.junit), junit(phases)) } catch (e) { stderr(`could not write ${a.junit}: ${e.message}\n`) }
  }
  if (provider === 'github' && env.GITHUB_STEP_SUMMARY) {
    try {
      const rows = phases.map(p => `| ${p.name} | ${WORDS[p.verdict] ?? p.verdict} | ${p.passed !== undefined ? `${p.passed} passed · ${p.failed} failed` : ''} |`)
      appendFileSync(env.GITHUB_STEP_SUMMARY, `## Quality Code: ${result}\n\n| Phase | Verdict | Tests |\n|---|---|---|\n${rows.join('\n')}\n`)
    } catch {}
    for (const p of phases.filter(x => ORDER[x.verdict] > 0)) (a.json ? stderr : stdout)(`::error title=Quality Code ${p.name}::${WORDS[p.verdict]}\n`)
  }
  return code
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) process.exitCode = await main()
